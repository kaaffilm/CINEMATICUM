/* Display-cache lifecycle tests. Synthetic decoder fixtures are not film acceptance. */
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const surfaces=[];
function createSurface(){
  const surface={width:0,height:0,pixel:null,getContext(){return {drawImage(video){surface.pixel=video.pixel;}};}};
  surfaces.push(surface);return surface;
}
const sandbox={window:{},document:{createElement:createSurface}};vm.createContext(sandbox);
const web=path.join(__dirname,'web');
for(const name of ['decoded-frame-cache.js','sequence-playback.js'])vm.runInContext(fs.readFileSync(path.join(web,name),'utf8'),sandbox,{filename:name});
const Cache=sandbox.window.CinematicumDecodedFrameCache;
const video={videoWidth:4,videoHeight:4,readyState:4,seeking:false,pixel:'first'};
const cache=new Cache({maxBytes:128,maxEntries:10,createSurface});
const first=cache.capture('source-a',0,video);video.pixel='second';
cache.capture('source-a',1,video);
assert.equal(cache.get('source-a',0),first,'Decoded pictures must survive a later decoder frame');
assert.equal(first.pixel,'first');
video.pixel='third';cache.capture('source-b',0,video);
assert.equal(cache.get('source-a',1),null,'The least recently used decoded surface must be evicted');
assert.equal(cache.stats().bytes,128);assert.equal(cache.stats().entries,2);
assert.equal(cache.get('source-a',.00001),null,'VFR/mixed-rate requests must not borrow nearby frames');
assert.equal(cache.get('different-hash-or-proxy',0),null,'Media identities must stay distinct');
const before=surfaces.length;
assert.equal(cache.capture('too-large',0,{...video,videoWidth:10000,videoHeight:10000}),null);
assert.equal(surfaces.length,before,'An over-budget source must be rejected before allocating pixels');
assert.equal(cache.capture('seeking',0,{...video,seeking:true}),null,'A pending seek must never be frozen as the requested picture');
assert.equal(cache.capture('unready',0,{...video,readyState:1}),null);
cache.clear();assert.equal(cache.stats().bytes,0);assert.equal(first.width,1);assert.equal(first.height,1);
const bounded=new Cache({maxBytes:1000,maxEntries:1,createSurface});
bounded.capture('source-a',0,video);bounded.capture('source-a',1,video);assert.equal(bounded.stats().entries,1);
const callbacks=new Map(),cancelled=[];let nextId=0;
const callbackVideo={...video,src:'file:///original.mp4',requestVideoFrameCallback(callback){callbacks.set(++nextId,callback);return nextId;},cancelVideoFrameCallback(id){cancelled.push(id);callbacks.delete(id);}};
const observed=new Cache({maxBytes:128,createSurface});
observed.observe(callbackVideo,'original');assert.equal(callbacks.size,1);
const stale=callbacks.get(1);observed.clear();stale(0,{mediaTime:0});
assert.equal(observed.stats().entries,0,'A callback delivered after reset must not repopulate cleared memory');
assert.equal(callbacks.size,0);assert.deepEqual(cancelled,[1]);
observed.observe(callbackVideo,'original');
const callback=callbacks.get(nextId);callbacks.delete(nextId);callbackVideo.pixel='presented';callback(0,{mediaTime:.25});
assert.equal(observed.get('original',.25).pixel,'presented');assert.equal(callbacks.size,1);
const replaced=callbacks.get(nextId);callbacks.delete(nextId);callbackVideo.src='file:///proxy.mp4';replaced(0,{mediaTime:.5});
assert.equal(observed.get('original',.5),null,'Changed decoder URLs must not contaminate the old source identity');
assert.equal(observed.stats().observers,0);assert.equal(callbacks.size,0);
observed.observe(callbackVideo,'proxy');observed.retain(new Set());assert.equal(observed.stats().observers,0);assert.equal(callbacks.size,0);
const failing=new Cache({maxBytes:128,createSurface:()=>({width:0,height:0,getContext(){return {drawImage(){throw Error('decoder lost');}};}})});
assert.equal(failing.capture('source',0,video),null);assert.equal(failing.stats().bytes,0);

// Exercise the shipped traversal, including a cache hit before native seek.
sandbox.window.CinematicumEditing={active:()=>true,pose:()=>({scale:1,opacity:1,x:0,y:0,rotation:0}),audioGain:()=>1,sourceFrame:(clip,frame)=>frame,trackingOffset:()=>({x:0,y:0})};
const drawn=[],context={save(){},restore(){},translate(){},rotate(){},drawImage(picture){drawn.push(picture);}};
let nativeTime=0,seeks=0;
const element={...video,videoWidth:4,videoHeight:4,duration:10,paused:true,playbackRate:1,pixel:'frame-0',src:'/original',get currentTime(){return nativeTime;},set currentTime(value){nativeTime=value;seeks++;this.seeking=true;},pause(){this.paused=true;},play(){this.paused=false;return Promise.resolve();}};
const media={kind:'video',el:element,requestUrl:'/original',disposed:false};
const project={id:'project-a',fps:24,width:4,height:4,titles:[],tracks:[],assets:[{id:'asset',kind:'video',sha256:'a'.repeat(64),width:4,height:4}],clips:[{id:'clip',asset_id:'asset',start:0,in:0,duration:48,track:0}]};
const playback=sandbox.window.CinematicumSequencePlayback;
const draw=(frame,playing=false)=>playback.draw({project,frame,context,width:4,height:4,mediaFor:()=>media,ensureAudio:()=>null,playing,activeIds:new Set(),revision:0});
draw(0);const decodedZero=drawn.at(-1);assert.notEqual(decodedZero,element);assert.equal(decodedZero.pixel,'frame-0');
draw(12);assert.equal(seeks,1);assert.equal(element.seeking,true);
element.seeking=false;element.pixel='frame-12';draw(12);assert.equal(drawn.at(-1).pixel,'frame-12');
draw(0);assert.equal(seeks,1,'Returning to a cached decoded timestamp must not flush the native decoder');assert.equal(drawn.at(-1),decodedZero);
project.assets[0].sha256='b'.repeat(64);draw(0);assert.equal(seeks,2,'Changed content hashes must invalidate lookup even if asset ID/path are reused');
playback.clear();assert.equal(playback.cacheStats().bytes,0);assert.equal(decodedZero.width,1);
let registrations=0,cancellations=0;
element.requestVideoFrameCallback=()=>++registrations;element.cancelVideoFrameCallback=()=>cancellations++;
element.seeking=false;nativeTime=.5;
const allocationsBefore=surfaces.length;
draw(12,true);assert.equal(registrations,0);assert.equal(surfaces.length,allocationsBefore);assert.equal(playback.cacheStats().bytes,0,'Ordinary forward playback must not copy decoded frames');
project.clips[0].reverse=true;draw(12,true);assert.equal(registrations,1);assert.equal(playback.cacheStats().observers,1);
project.clips[0].reverse=false;draw(12,true);assert.equal(cancellations,1);assert.equal(playback.cacheStats().observers,0,'Forward resume must release paused/reverse frame callbacks');
playback.clear();
console.log('Decoded frame cache: bounded allocation, LRU, source identity, seek, callback and reset checks passed.');
